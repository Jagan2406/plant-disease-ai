export function AvailableRecordFields({ record }) {
  const fields = [["Disease", record?.disease_name], ["Causal agent", record?.causal_agent], ["Agent type", record?.causal_agent_type], ["Evidence", record?.evidence_strength]].filter(([, value]) => value != null && String(value).trim());
  if (!fields.length) return null;
  return <section className="available-record-fields">{fields.map(([label, value]) => <div key={label}><span>{label}</span><strong>{String(value)}</strong></div>)}</section>;
}

export function CompactExplanationMetrics({ result }) {
  const cam = result?.gradcam || {};
  const outside = cam.cam_inside_leaf == null ? null : `${((1 - Number(cam.cam_inside_leaf)) * 100).toFixed(3)}%`;
  const items = [["CAM inside leaf", percent(cam.cam_inside_leaf, 3)], ["CAM outside leaf", outside], ["Leaf coverage", percent(cam.leaf_coverage, 3)], ["Activation resolution", resolutionText(cam.activation_resolution)]];
  return <div className="compact-metrics">{items.map(([label, value]) => value && <Metric key={label} label={label} value={value} />)}</div>;
}

