import { Activity, AlertTriangle, CheckCircle2, CircleHelp, ImageOff, Leaf, ShieldCheck } from "lucide-react";
import { useState } from "react";

export const formatDisease = (value = "") => String(value).replaceAll("___", " · ").replaceAll("__", " · ").replaceAll("_", " ");
export const percent = (value, digits = 2) => Number.isFinite(Number(value)) ? `${(Number(value) * 100).toFixed(digits)}%` : null;
export const numberText = (value, digits = 4) => Number.isFinite(Number(value)) ? Number(value).toFixed(digits) : null;
export const resolutionText = (value) => Array.isArray(value) && value.length ? value.join(" × ") : null;
export const asItems = (value) => Array.isArray(value) ? value.filter((item) => typeof item === "string" && item.trim()) : [];
export const isHealthy = (result) => /healthy/i.test(`${result?.predicted_class || ""} ${result?.knowledge?.record?.causal_agent_type || ""}`);
export const isViral = (record) => /virus|viral/i.test(`${record?.causal_agent_type || ""} ${record?.class_name || ""}`);

function Metric({ label, value }) {
  if (value == null || value === "") return null;
  return <div className="data-metric"><span>{label}</span><strong>{value}</strong></div>;
}

export function ConfidenceMeter({ result, compact = false }) {
  const value = Number(result?.confidence);
  if (!Number.isFinite(value)) return null;
  const bounded = Math.max(0, Math.min(1, value));
  const circle = 2 * Math.PI * 43;
  const uncertain = result?.grounded_context?.uncertain === true;
  const status = uncertain ? "LOW CONFIDENCE" : result?.grounded_context?.status === "grounded" ? "GROUNDING THRESHOLD MET" : "MODEL CONFIDENCE";
  return (
    <div className={`confidence-meter ${compact ? "compact" : ""}`}>
      <div className="confidence-gauge">
        <svg viewBox="0 0 100 100" role="img" aria-label={`Model confidence ${percent(bounded)}`}>
          <circle className="gauge-track" cx="50" cy="50" r="43" />
          <circle className="gauge-value" cx="50" cy="50" r="43" style={{ "--gauge-circumference": circle, "--gauge-progress": circle * bounded }} />
        </svg>
        <div className="gauge-center"><strong>{percent(bounded, 2)}</strong><span>CONFIDENCE</span></div>
      </div>
      <div className={`confidence-status ${uncertain ? "uncertain" : ""}`}><i />{status}</div>
    </div>
  );
}

export function ResultImageStrip({ result, previewUrl }) {
  const [active, setActive] = useState("original");
  const tabs = [
    ["original", "ORIGINAL"],
    ["mask", "SAM 2.1 MASK"],
    ["leaf", "LEAF ONLY"],
    ["cam", "GRAD-CAM++"],
  ];
  const gradcam = result?.gradcam || {};
  const maskShape = resolutionText(result?.segmentation_metadata?.mask_shape);
  const activation = resolutionText(gradcam.activation_resolution);
  const imageSources = {
    original: result?.analysis_images?.original || previewUrl,
    mask: result?.analysis_images?.sam2_mask,
    leaf: result?.analysis_images?.leaf_only,
    cam: result?.analysis_images?.gradcam_pp,
  };
  const image = imageSources[active];
  const descriptions = {
    original: "Uploaded image supplied to the segmentation stage.",
    mask: "Leaf segmentation generated by SAM 2.1; white boundary marks the real mask edge.",
    leaf: "Actual masked leaf image supplied to the Swin Transformer classifier.",
    cam: "Actual Grad-CAM++ activation overlay for the predicted class.",
  };
  return (
    <section className="image-strip-section">
      <div className="section-title-row"><div><span className="technical-label">VISUAL ANALYSIS</span><h2>Image evidence</h2></div><span className="section-index">01—04</span></div>
      <div className="image-tab-row" role="tablist" aria-label="Analysis images">
        {tabs.map(([key, label], index) => <button key={key} className={active === key ? "selected" : ""} type="button" role="tab" aria-selected={active === key} onClick={() => setActive(key)}><span>0{index + 1}</span>{label}</button>)}
      </div>
      <div className="image-evidence">
        {image ? (
          <img className="evidence-original" src={image} alt={`${tabs.find(([key]) => key === active)?.[1] || "Analysis"} visualization`} />
        ) : (
          <div className="artifact-unavailable">
            <ImageOff size={23} />
            <strong>{active === "cam" ? "CAM image not provided by API" : active === "mask" ? "Mask image not provided by API" : "Leaf-only image not provided by API"}</strong>
            <p>The current API response contains numerical explanation and segmentation metrics, but not image pixel data for this view.</p>
            {active === "cam" && <div className="artifact-metrics">
              <Metric label="Activation resolution" value={activation} />
              <Metric label="CAM output shape" value={resolutionText(gradcam.cam_shape)} />
              <Metric label="CAM minimum" value={numberText(gradcam.cam_min)} />
              <Metric label="CAM maximum" value={numberText(gradcam.cam_max)} />
            </div>}
            {active === "mask" && maskShape && <span className="artifact-measure">Mask resolution · {maskShape}</span>}
          </div>
        )}
        <span className="evidence-corner">VIEW / {tabs.findIndex(([key]) => key === active) + 1}</span>
      </div>
      <div className="evidence-footnote"><ShieldCheck size={14} /> No mask or heatmap has been synthesized. This view only presents artifacts returned by the API.</div>
    </section>
  );
}

export function PredictionDetails({ result }) {
  const gradcam = result?.gradcam || {};
  const meta = result?.segmentation_metadata || {};
  const segmentation = result?.fallback_used === true ? "Fallback used" : result?.fallback_used === false ? "Primary mask selected" : null;
  const items = [
    ["Predicted class", result?.predicted_class],
    ["Class ID", Number.isInteger(result?.class_id) ? String(result.class_id) : null],
    ["Confidence", percent(result?.confidence)],
    ["Mask area ratio", percent(result?.mask_area_ratio, 3)],
    ["Segmentation status", segmentation],
    ["Mask resolution", resolutionText(meta.mask_shape)],
    ["Grad-CAM activation", resolutionText(gradcam.activation_resolution)],
    ["Leaf coverage", percent(gradcam.leaf_coverage, 3)],
    ["CAM inside leaf", gradcam.cam_inside_leaf == null ? null : percent(gradcam.cam_inside_leaf, 3)],
  ];
  return (
    <section className="details-section">
      <div className="section-title-row"><div><span className="technical-label">MODEL OUTPUT</span><h2>Prediction details</h2></div><span className="section-index">RESPONSE FIELDS</span></div>
      <div className="details-grid">{items.map(([label, value]) => <Metric key={label} label={label} value={value} />)}</div>
    </section>
  );
}

export function TopPredictions({ result }) {
  const predictions = Array.isArray(result?.top_k_predictions) ? result.top_k_predictions.slice(0, 5) : [];
  if (!predictions.length) return null;
  return (
    <section className="top-predictions">
      <div className="section-title-row"><div><span className="technical-label">ALTERNATIVE CLASSES</span><h2>Top predictions</h2></div><span className="section-index">{String(predictions.length).padStart(2, "0")} RANKED</span></div>
      <ol>{predictions.map((prediction, index) => {
        const probability = Number(prediction.confidence);
        const isWinner = prediction.class_id === result.class_id;
        return <li key={`${prediction.class_id}-${prediction.class_name}`} className={isWinner ? "winner" : ""}>
          <span className="rank-label">#{String(index + 1).padStart(2, "0")}</span>
          <div className="prediction-name"><strong>{formatDisease(prediction.class_name)}</strong><span>ID {prediction.class_id}</span></div>
          <div className="prediction-score"><div><i style={{ width: `${Number.isFinite(probability) ? Math.max(0, Math.min(1, probability)) * 100 : 0}%` }} /></div><strong>{percent(probability, 2) || "—"}</strong></div>
        </li>;
      })}</ol>
      <p className="rank-footnote">Scores are the classifier probabilities returned in this prediction response.</p>
    </section>
  );
}


export function DataSection({ title, eyebrow, value, icon: Icon = Leaf, emphasis = false }) {
  const items = Array.isArray(value) ? value : typeof value === "string" && value.trim() ? [value] : [];
  if (!items.length) return null;
  return <section className={`data-section ${emphasis ? "emphasis" : ""}`}><span className="technical-label">{eyebrow}</span><div className="data-section-heading"><Icon size={18} /><h2>{title}</h2></div>{items.map((item, index) => <p key={index}>{item}</p>)}</section>;
}

